#!/usr/bin/env python3
"""
build_site.py — assemble index.html from the template, the stylesheets, the
scripts and the notice data.

    python3 parser/build_site.py

Inputs
    app.template.html      markup + the early theme script; carries the
                           /*__CSS__*/ and /*__JS__*/ placeholders
    assets/css/*.css       stylesheets, concatenated in CSS_FILES order
    assets/js/**/*.js      scripts, concatenated in JS_FILES order
    data/notices.json      generated by parser/build_data.py, substituted into
                           the /*__DATA__*/ placeholder inside
                           assets/js/data/notices.js

Output
    index.html             one self-contained file — no external CSS, no
                           external JS, no runtime fetch, no CDN

Everything is inlined on purpose. The page has to work from file://, from a
phone with no signal, and inside sandboxed previews, so a <link> to a
stylesheet, a <script src> or a fetch() for the data would each break a
documented feature. That is also why the scripts are concatenated into a
single classic <script> rather than loaded as ES modules: `import` over
file:// is blocked by CORS.

Because they share one script scope, the JS files see each other's top-level
declarations directly. Order therefore matters, and JS_FILES is that order.

The build is deterministic: the same sources always produce a byte-identical
index.html. The only timestamp in the output is the one build_data.py already
recorded inside notices.json.
"""

import hashlib
import json
import re
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# Concatenation order is load-bearing — this IS the cascade.
#   tokens      must come first; everything else reads its custom properties
#   base        document defaults
#   layout      page chrome
#   components  the bulk of the UI
#   responsive  narrow-viewport overrides, so it must follow components
#   print       last, so it can override anything for paper
CSS_FILES = [
    "tokens.css",
    "base.css",
    "layout.css",
    "components.css",
    "responsive.css",
    "print.css",
]

# Concatenation order is load-bearing — one shared script scope.
#
# Nearly every cross-file reference sits inside a function body and is not
# evaluated until boot() runs, so most of this order is for readability. Two
# constraints are real:
#   data/notices.js  decodes the dataset at load time, so it must come after
#                    nothing in particular but before any load-time reader
#   app.js           ends with boot(), which calls into every feature, so it
#                    must come last
JS_FILES = [
    "core/constants.js",
    "core/dom.js",
    "core/numbers.js",
    "core/dates.js",
    "core/language.js",
    "data/notices.js",
    "features/maps.js",
    "features/results.js",
    "features/rolls.js",
    "features/search.js",
    "features/notice-list.js",
    "features/preferences.js",
    "app.js",
]

BANNER = (
    "<!--\n"
    "  GENERATED FILE — DO NOT EDIT.\n"
    "  Built by parser/build_site.py from:\n"
    "    app.template.html   (markup and the early theme/language script)\n"
    "    assets/css/*.css    (stylesheets, concatenated in CSS_FILES order)\n"
    "    assets/js/**/*.js   (scripts, concatenated in JS_FILES order)\n"
    "    data/notices.json   (notice data, inlined so the page works offline)\n"
    "  Edit those sources and re-run the build; changes made here are lost.\n"
    "-->"
)


def die(msg: str) -> None:
    sys.exit(f"build_site: {msg}")


def read(path: str, what: str) -> str:
    if not os.path.exists(path):
        die(f"missing {what}: {os.path.relpath(path, ROOT)}")
    text = open(path, encoding="utf-8").read()
    if not text.strip():
        die(f"{what} is empty: {os.path.relpath(path, ROOT)}")
    return text


def strip_file_header(text: str) -> str:
    """Drop the leading /* ... */ header comment from a source file.

    Each file in assets/ opens with a block comment explaining what it holds
    and warning that it is assembled rather than linked. That note is for
    whoever opens the source; it means nothing to a browser, and nineteen of
    them inlined into every page load cost about 3.5 KB of the performance
    budget.

    Only the very first comment is removed, and only when the file starts
    with it. Every other comment — including the explanations sitting above
    individual rules and functions — ships untouched. This is not
    minification: no code is rewritten, shortened or reordered.
    """
    if not text.startswith("/*"):
        return text
    end = text.find("*/")
    if end < 0:
        return text
    return text[end + 2:].lstrip("\n")


def bundle(subdir: str, manifest: list, ext: str, what: str) -> str:
    """Concatenate the manifest's files, refusing to silently skip any."""
    base = os.path.join(ROOT, "assets", subdir)
    if not os.path.isdir(base):
        die(f"assets/{subdir} does not exist")

    # Catch a file that was added to the folder but never wired into the
    # build — otherwise it silently never ships.
    on_disk = set()
    for root, _dirs, files in os.walk(base):
        for f in files:
            if f.endswith(ext):
                on_disk.add(os.path.relpath(os.path.join(root, f), base).replace(os.sep, "/"))
    orphans = sorted(on_disk - set(manifest))
    if orphans:
        die(f"{what} not listed in the build manifest, so they would never ship: {orphans}")

    parts = []
    for name in manifest:
        body = strip_file_header(read(os.path.join(base, name), what)).rstrip()
        if not body:
            die(f"{what} {name} is nothing but its header comment")
        parts.append(f"/* ===== {name} ===== */\n{body}")
    return "\n\n".join(parts) + "\n"


def main() -> None:
    tpl_path = os.path.join(ROOT, "app.template.html")
    dat_path = os.path.join(ROOT, "data", "notices.json")
    out_path = os.path.join(ROOT, "index.html")

    html = read(tpl_path, "template")
    raw = read(dat_path, "notice data").strip()

    for marker in ("/*__CSS__*/", "/*__JS__*/"):
        if marker not in html:
            die(f"template is missing the {marker} placeholder")

    try:
        data = json.loads(raw)
    except json.JSONDecodeError as exc:
        die(f"data/notices.json is not valid JSON — {exc}")

    notices = data.get("notices")
    if not isinstance(notices, list) or not notices:
        die("data/notices.json contains no notices — refusing to publish an empty site")
    missing_id = [i for i, n in enumerate(notices) if not n.get("id")]
    if missing_id:
        die(f"notice records without an id at index {missing_id}")

    css = bundle("css", CSS_FILES, ".css", "stylesheet(s)")
    js = bundle("js", JS_FILES, ".js", "script(s)")

    # Inlining hazard: the HTML parser ends a <script> at the first literal
    # "</script>" even inside a JS string or comment, which would silently
    # truncate the bundle and spray the rest of the code onto the page. Same
    # for "</style>". Cheap to check, catastrophic to miss.
    if "</script" in js.lower():
        die("a script source contains a literal '</script>' — it would terminate "
            "the inlined block; split it (e.g. '<\\/script')")
    if "</style" in css.lower():
        die("a stylesheet contains a literal '</style>' — it would terminate the "
            "inlined block")

    html = html.replace("/*__CSS__*/", css)
    html = html.replace("/*__JS__*/", js)

    # /*__DATA__*/ lives inside assets/js/data/notices.js, so it only exists
    # once the scripts above have been spliced in.
    if "/*__DATA__*/" not in html:
        die("the assembled page has no /*__DATA__*/ placeholder — "
            "assets/js/data/notices.js should declare `const DATA = /*__DATA__*/;`")
    html = html.replace("/*__DATA__*/", raw)

    html = html.replace("<!DOCTYPE html>", "<!DOCTYPE html>\n" + BANNER, 1)

    open(out_path, "w", encoding="utf-8").write(html)

    # ---------------------------------------------------------------- sw.js
    # The cache name used to be a hand-typed "bb-roll-vN". Forgetting to bump
    # it shipped a correct index.html that returning visitors never saw,
    # because the old service worker kept serving the old shell -- the exact
    # failure mode the network-first HTML strategy exists to avoid. Deriving
    # it from the bundle means it is impossible to forget and impossible to
    # bump when nothing actually changed.
    digest = hashlib.sha1((css + js).encode("utf-8")).hexdigest()[:8]
    sw_path = os.path.join(ROOT, "sw.js")
    sw = read(sw_path, "service worker")
    new_sw, n = re.subn(r'const CACHE = "bb-roll-[^"]*";',
                        f'const CACHE = "bb-roll-{digest}";', sw, count=1)
    if n != 1:
        die('sw.js has no `const CACHE = "bb-roll-...";` line to stamp')
    if new_sw != sw:
        open(sw_path, "w", encoding="utf-8").write(new_sw)
    print(f"  service worker cache: bb-roll-{digest}"
          f"{'' if new_sw != sw else ' (unchanged)'}")

    size = os.path.getsize(out_path)
    print(f"wrote {out_path}")
    print(f"  {size // 1024} KB · {len(notices)} notices")
    print(f"  {len(CSS_FILES)} stylesheets ({len(css) // 1024} KB) + "
          f"{len(JS_FILES)} scripts ({len(js) // 1024} KB) inlined")


if __name__ == "__main__":
    main()
